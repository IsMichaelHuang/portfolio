// Pure helpers for turning pinned GitHub repos into src/data/projects.ts.
// Every repo field is untrusted: the owner of a pin may be someone else.
import type { Project } from '../src/data/projects.ts'

export const OWNER = 'IsMichaelHuang'
const SELF = `${OWNER}/portfolio`.toLowerCase()

export interface GitHubRepo {
  name: string
  nameWithOwner: string
  description: string | null
  url: string
  homepageUrl: string | null
  primaryLanguage: { name: string } | null
  repositoryTopics: { nodes: { topic: { name: string } }[] }
}

export const QUERY = `{
  user(login: ${JSON.stringify(OWNER)}) {
    pinnedItems(first: 6, types: REPOSITORY) {
      nodes {
        ... on Repository {
          name
          nameWithOwner
          description
          url
          homepageUrl
          primaryLanguage { name }
          repositoryTopics(first: 10) { nodes { topic { name } } }
        }
      }
    }
  }
}`

const isHttps = (s: string): boolean => {
  try {
    return new URL(s).protocol === 'https:'
  } catch {
    return false
  }
}

export function toProject(repo: GitHubRepo): Project | null {
  if (!repo.url.startsWith('https://github.com/')) return null
  const topics = repo.repositoryTopics.nodes.map((n) => n.topic.name)
  const lang = repo.primaryLanguage?.name
  const project: Project = {
    id: repo.nameWithOwner.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    title: repo.name
      .replace(/[-_]/g, ' ')
      .replace(/\b\w/g, (c) => c.toUpperCase()),
    tags: topics.length ? topics : lang ? [lang] : [],
    repoUrl: repo.url,
  }
  if (repo.description) project.description = repo.description
  if (repo.homepageUrl && isHttps(repo.homepageUrl)) {
    project.liveUrl = repo.homepageUrl
  }
  return project
}

export function selectRepos(nodes: (GitHubRepo | null)[]): GitHubRepo[] {
  return nodes.filter(
    (n): n is GitHubRepo =>
      n !== null && n.nameWithOwner.toLowerCase() !== SELF,
  )
}

// The header is static text; repo data only enters via JSON.stringify.
export function buildProjectsFile(projects: Project[]): string {
  return `/**
 * Project Data - generated by scripts/fetch-pinned.ts from GitHub
 * pinned repositories. Do not edit by hand; edits are overwritten.
 */

export interface Project {
  id: string;
  title: string;
  description?: string;
  tags: string[];
  repoUrl?: string;
  liveUrl?: string;
}

export const projects: Project[] = ${JSON.stringify(projects, null, 2)};
`
}
